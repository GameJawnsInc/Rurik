"""Assemble a whole Bloated map file from typed parameters.

`mapfile.py` proved the container round-trips (698 of 698). `terrain.py` and
`pathchunk.py` proved their chunks do (349 of 349 each). This module is the
authoring direction of all three: it takes **numbers** -- dims, a height field, a
tile table, a navmesh, a world rect -- and emits a complete `ffna` type-3 map
payload the client's own loader rules accept.

    with Archive() as ar:
        mf, rep = build_like(46196, ar)      # row 46196, from its parameters
        assert mf.encode() == ar.read(row)   # BYTE-IDENTICAL, 8,471 bytes
        print(rep.summary())                 # and what was generated vs carried

    mf, rep = build_flat(64, 64, height=-1000.0, archive=ar)   # from nothing

**BYTE-IDENTITY IS HALF A RESULT AND THE WEAKER HALF.** A program that copies
8,471 bytes passes it, and the licensing constraint below makes a copying builder
the *expected* shape for part of the file. So every build returns a `BuildReport`
that says, per chunk, whether the bytes were GENERATED by our encoders from typed
values or CARRIED verbatim out of the archive, and the carried ones are named
individually rather than lumped. Read `rep.summary()`, not just the equality.

MEASURED on row 46196 (`vault/dat_study/Gw.dat`, 2026-08-11), 8,471 bytes:

    generated  7,814 B  92.24%   framing 149, Terrain 7,165, Path 419,
                                 Map Parameters 41, Dependencies 40
    carried      657 B   7.76%   Props 51, Zones 42, Mission 69,
                                 Environment 178, Light 7, Shore 17,
                                 Sight 44, Sound 17            (425 B, 8 kinds)
                                 + the five FINDINGS 14 constants      (232 B)

The brief for this rung predicted ~93.4%; the 1.2-point shortfall is the Header
(8 B) and the Water Dependencies chunk (197 B), both of which this module carries
rather than generates because `FINDINGS 14` names them among the five constants
that may not enter the repo. Generating the Header instead -- FINDINGS 17.5 says the
client's own code writes exactly `{u32 0x39871124, u32 3}`, so we could -- moves
the figure to 92.34%. Nothing in the rung hangs on either decision, and carrying
is the conservative direction.

**A STRICTER NUMBER, because the headline flatters the terrain chunk.** Of those
7,165 generated terrain bytes, 2,312 reach `terrain.py`'s encoder as `bytes`
objects it emits without transforming (tiles 1,024, shade 1,024, tag 3's bit
field 256, the two 4-byte tile tables). `mapfile.byte_census` counts those as
carried and so does `BuildReport.strict_generated`: **5,502 B, 64.95%** on
`build_like`. On `build_flat` the same arrays are produced from scalars this
module was handed, so they are not ArenaNet bytes at all -- which is exactly why
the split is reported per build and not stated once as a property of the format.

THE PROVENANCE CONSTRAINT IS THE DESIGN, not a caveat on it. `FINDINGS 14`:
five mandatory chunks are byte-identical ArenaNet constants across all 349 maps
-- `0x20000000` (8 B), `0x2000000A` (13 B), `0x2000000E` (9 B), `0x20000006`
(5 B) and `0x21000006` (197 B), 232 bytes per map. `CLAUDE.md`'s provenance gate
says zero ArenaNet bytes in the repo, ever, and that it is not retrofittable. So
those 232 bytes are **read from the owner's own archive at run time** and this
module REFUSES to build without one (`NoConstants`). They are never stored here:
not as files, not as hex literals, not as base64, not in a test fixture --
`test_mapbuild.py` reads them from the vault too and skips when it cannot.

The donor is deliberately **not** the map being rebuilt, by default. FINDINGS 14's
claim is that these five are constant across the corpus; reading them out of a
different map and still landing byte-identical on row 46196 is a check that can
fail, and reading them out of row 46196 itself is not one.

**AND ONE OF THE FIVE IS NOT CONSTANT.** MEASURED here, 2026-08-11, over a
sample of 12 maps: `0x20000000`, `0x2000000A`, `0x2000000E` and `0x21000006` are
byte-identical on 12 of 12, and `0x20000006` (Water) takes **two** values --
3 maps carry one, 9 carry the other, and they differ in exactly one byte of the
five (FINDINGS 3 reads that chunk as a u32 and a flag; the values themselves stay
in the archive, which is why they are described and not quoted here).
FINDINGS 14 says as much in a parenthesis ("5 B, two
values") and the first version of this module trusted the sentence rather than
the parenthesis; row 46196 and row 7982 both happened to agree with their donors
and it round-tripped anyway, which is exactly the shape of a bug that ships. So
`build_like` VERIFIES each borrowed constant against the map it is rebuilding,
substitutes that map's own bytes where they differ, and NAMES the substitution in
the report. Four of the five are corpus constants and the report says which.

WHAT "GENERATED" MEANS HERE, precisely, because the word does a lot of work:

  * the bytes were emitted by our encoders from typed values, with every size
    and count re-derived at encode time (`mapfile` re-derives the chunk table's
    `size`; `terrain` and `pathchunk` re-derive every record size and count);
  * for `build_like` the VALUES came from the source map -- that is what "like"
    means, and it is how a specific map gets reproduced;
  * for `build_flat` the values came from the caller's arguments and nothing
    else.

Generated does NOT mean "understood". Seventeen chunk kinds are still carried
opaquely and each is a rung of its own; the report names them so that stays
visible.

THE CHUNK ORDER IS THE FILE'S, NOT A CANONICAL ONE. FINDINGS 3 measured a
single total order across the corpus (321 ordered pairs, 0 contradictory), but
`build_like` reproduces the source's own order and `build_flat` takes an order
that must be a subsequence of a reference the caller supplies -- measured at run
time from a real map, never a list typed in here.

SCOPE. Nothing here opens a file for writing and nothing places bytes in an
archive -- that is `datplan.py` and `datwrite.py`. The CLI's `--out` writes a
built payload to disk and REFUSES any path inside the working tree, because a
`build_like` output is derived ArenaNet data.

UNVERIFIED against a client: nothing built here has been loaded. `gates()`
reproduces every open-time rule FINDINGS 17.4/17.5 states, and its control is
that a shipped retail map must pass all of them -- a gate a real map fails is our
bug, not the map's.

    python toolkit/mapdata/mapbuild.py                    # row 46196, reported
    python toolkit/mapdata/mapbuild.py --row 46196 --verbose
    python toolkit/mapdata/mapbuild.py --flat 64x64
    python toolkit/mapdata/mapbuild.py --flat 32x32 --out <path outside the repo>
"""

