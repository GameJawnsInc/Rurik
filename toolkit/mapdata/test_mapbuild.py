def section1():
    print("\n-- 1. Map Parameters, packed by hand and read back")
    rect = (-3072.0, -6144.0, 3072.0, 6144.0)
    uid = bytes(range(16))
    blob = encode_map_parameters(rect, flags=0x03000020, uuid=uid)
    check(len(blob) == MAP_PARAMS_SIZE == 41,
          "the payload is 41 bytes, the client's `size >= 41` gate", f"{len(blob)}")
    check(int.from_bytes(blob[0:4], "little") == 0x5943EEEF and blob[4] == 2,
          "signature 0x5943EEEF then the version as a SINGLE BYTE at +4")
    check(struct.unpack_from("<4f", blob, 5) == rect,
          "so the four rect floats start at the UNALIGNED offset +5",
          "a writer that pads to align them emits a chunk the client rejects")
    check(int.from_bytes(blob[0x15:0x19], "little") == 0x03000020
          and blob[0x19:0x29] == uid,
          "flags at +0x15 and the 16-byte content id at +0x19")
    got = decode_map_parameters(blob)
    check(got[0] == rect and got[1] == 0x03000020 and got[2] == uid,
          "and it decodes back to the values that went in")

    # THE NAMED CONTROL, and its outcome is not the one this check first
    # asserted. The mistake FINDINGS 17.4 warns about is a packer that writes
    # the version as a u32 and so aligns the rect to +8. Those bytes are NOT
    # refused -- by us or by the client: the low byte of a u32 2 is still 2, so
    # the signature gate and the version gate both pass and the loader copies
    # four floats of rubbish into the world rect with no validation whatever.
    # The failure is SILENT, which is exactly why `encode_map_parameters` packs
    # `<IB` and the rect separately instead of one tidy struct.
    aligned = (struct.pack("<II", 0x5943EEEF, 2) + struct.pack("<4f", *rect)
               + struct.pack("<I", 0) + uid)
    aligned_rect = decode_map_parameters(aligned)[0]
    check(len(aligned) == 44 and aligned_rect != rect,
          "the aligned-version-word packer passes both hard gates and yields a "
          "DIFFERENT rect -- it fails silently, it does not get refused",
          f"{aligned_rect} instead of {rect}; a writer that pads to align the "
          f"floats misplaces the world and gets no error for it")
    check(blob[5:9] != aligned[5:9],
          "and our encoder does not produce those bytes",
          "the rect starts at +5 here and at +8 there")
    check(refuses(decode_map_parameters, blob[:16]),
          "so is a 16-byte payload, the one size with a gate of its own")
    check(refuses(decode_map_parameters, b"\x00" * 41),
          "so is a payload with the wrong signature")
    bad_ver = bytearray(blob)
    bad_ver[4] = 3
    check(refuses(decode_map_parameters, bytes(bad_ver)),
          "so is version 3")
    check(refuses(encode_map_parameters, rect, uuid=b"\x00" * 15),
          "and a 15-byte content id will not encode")

    r = default_rect(32, 32)
    packed = struct.pack("<4f", *r)
    check(r == (-0.0, -0.0, 3072.0, 3072.0) and packed[3] == 0x80,
          "default_rect(32,32) reproduces row 46196's LITERAL NEGATIVE ZERO",
          "the client's constructor formula; the sign bit is really set")
    check(default_rect(128, 64) == (-6144.0, -3072.0, 6144.0, 3072.0),
          "and centres a 128x64 grid the way that formula does")


def section2():
    print("\n-- 2. the provenance gate, on this module's own source")
    src = open(mapbuild.__file__, "rb").read()
    text = src.decode("utf-8", "replace")
    # A payload of ArenaNet bytes could only be here as a literal. Look for the
    # shapes: a long bytes literal, a hex blob, base64, or an embedded file.
    long_hex = [w for w in text.replace('"', " ").replace("'", " ").split()
                if len(w) >= 24 and all(c in "0123456789abcdefABCDEF" for c in w)]
    check(not long_hex, "no hex literal long enough to be a borrowed constant",
          f"{long_hex[:2]}")
    check("fromhex" not in text and "b64decode" not in text,
          "no bytes.fromhex and no base64 decode anywhere in the module")
    # Read the module's own syntax tree rather than its text: a payload could
    # only be here as a bytes constant, and the smallest of the five is 5 bytes.
    big = [c.value for c in ast.walk(ast.parse(text))
           if isinstance(c, ast.Constant) and isinstance(c.value, bytes)
           and len(c.value) > 2]
    check(not big, "no bytes literal in the module is longer than two bytes",
          f"the smallest FINDINGS 14 constant is 5 B; found {big[:2]}")
    check(mapbuild.BORROWED_BYTES == sum(BORROWED_SIZES.values()) == 232,
          "the module states the 232 borrowed bytes as a SIZE and nothing more")

    root = mapbuild.REPO_ROOT
    check(os.path.isfile(os.path.join(root, "CLAUDE.md")),
          "REPO_ROOT resolves to the actual repo root", root)
    check(refuses(resolve_out, os.path.join(root, "toolkit", "built.ffna")),
          "writing a built map into the working tree is REFUSED")
    check(refuses(resolve_out, os.path.join(root, "x.ffna")),
          "including at the repo root itself")
    # A git WORKTREE's repo root is not the main checkout's, and a built map
    # written into the other tree is under version control just the same. This
    # went red before `working_tree_roots` existed: from the worktree this rung
    # was developed in, <main>/toolkit/out.dat was ALLOWED.
    #
    # The other tree is resolved HERE, out of `.git` directly, and NOT by asking
    # `mapbuild.working_tree_roots()` what it thinks the trees are. The first
    # version did ask, and a sabotage that crippled that function to return one
    # root passed this check 98 to 0 -- the defect and the oracle were the same
    # code. In a plain checkout `other` is the repo root, so the check still
    # asserts something and the count does not move between the two layouts.
    other = root
    dotgit = os.path.join(root, ".git")
    if os.path.isfile(dotgit):
        line = open(dotgit, encoding="utf-8", errors="replace").read().strip()
        gitdir = os.path.abspath(os.path.join(root, line.split(":", 1)[1].strip()))
        while os.path.basename(gitdir) != ".git" and os.path.dirname(gitdir) != gitdir:
            gitdir = os.path.dirname(gitdir)
        other = os.path.dirname(gitdir)
    check(refuses(resolve_out, os.path.join(other, "toolkit", "built.ffna")),
          "and the OTHER checkout of this repo is refused too",
          f"{other} -- read out of .git here, not from the module under test; "
          f"{'a worktree, so this is the main checkout' if other != root else 'a plain checkout, so it is this tree'}")
    inside_vault = vaultpath.vault_path("builds", "x.ffna")
    check(resolve_out(inside_vault) == os.path.abspath(inside_vault),
          "and the gitignored vault is allowed by name, not by prefix",
          "the vault sits INSIDE the repo root in the main checkout")


def section3():
    print("\n-- 3. a whole map from nothing but numbers")
    consts = placeholder_constants()
    mf, rep = build_flat(64, 32, height=-1000.0, tiles=3, tile=1,
                         constants=consts, donor_row="placeholder")
    blob = mf.encode()
    parts = walk(blob)
    ids = [cid for cid, _p in parts]
    check(len(blob) == rep.total and len(parts) == len(rep.chunks) == 8,
          "the report's byte total and chunk count are the file's",
          f"{len(blob)} B, {len(parts)} chunks")
    check(rep.framing == 5 + 8 * len(parts) == 69,
          "framing is the magic, the type byte and the chunk table", "69 B")
    check(sum(len(p) for _c, p in parts) + rep.framing == len(blob),
          "and every byte of the file is either framing or a chunk payload")
    check(rep.carried == rep.borrowed == 232,
          "everything carried is a FINDINGS 14 constant; nothing else is copied",
          f"carried {rep.carried} B, borrowed {rep.borrowed} B")
    check(rep.generated == len(blob) - 232,
          "so all the other bytes were generated here", f"{rep.generated} B")

    check(refuses(MapFile.decode, blob),
          "a STRICT decode refuses this file, and should: the placeholder "
          "0x21000006 is our zero bytes and not a Dependencies chunk",
          "which is also the check that these placeholders are not ArenaNet's")
    rt = MapFile.decode(blob, strict=False)
    check(rt.ffna_type == 3 and rt.ids == ids,
          "it decodes back through mapfile.MapFile as an ffna type-3 map")
    check([c.chunk_id for c in rt.failures()] == [mapbuild.WATER_DEPS_CHUNK],
          "and the ONE chunk it could not read is the placeholder, named")
    trn = rt.terrain()
    check(isinstance(trn, Terrain) and (trn.dim_x, trn.dim_y) == (64, 32),
          "and its terrain chunk decodes to the dims that were asked for",
          f"{trn.dim_x}x{trn.dim_y}")
    check(len(trn.heights) == 64 * 32 and set(trn.heights) == {-1000.0},
          "with the height field the caller passed as ONE NUMBER, broadcast",
          f"{len(trn.heights)} samples")
    check(len(trn.table_a) == 3 and len(trn.shadow) == 2 * 1,
          "the tile table it asked for and one shadow block per 32x32 chunk")
    check(Terrain.decode(chunk_map(blob)[TERRAIN_CHUNK]).encode()
          == chunk_map(blob)[TERRAIN_CHUNK],
          "and that chunk survives a decode/encode round trip of its own")

    rect = decode_map_parameters(chunk_map(blob)[MAP_PARAMS_CHUNK])[0]
    check(rect[2] - rect[0] == 64 * 96.0 and rect[3] - rect[1] == 32 * 96.0,
          "the rect is the grid at 96.0 units a cell, on both axes", f"{rect}")
    # The centring formula re-derived here rather than compared to itself. Note
    # it is NOT symmetric on an odd chunk count: 32 cells is one chunk, so the
    # y range is [-0.0, 3072] and not [-1536, 1536]. That asymmetry is the
    # client's own and row 46196 ships it.
    want = []
    for dim in (64, 32):
        c = dim // 32
        want.append((-(float(c >> 1) * 3072.0), float(c - (c >> 1)) * 3072.0))
    check(rect == (want[0][0], want[1][0], want[0][1], want[1][1]),
          "and it is the client's own constructor formula, re-derived here",
          f"{rect}")

    bad = [n for n, ok, _d in gates(mf) if not ok]
    check(not bad, "every open-time rule FINDINGS 17.4/17.5 states is satisfied",
          "; ".join(bad) or f"{len(gates(mf))} gates")

    check(refuses(build_flat, 30, 32, constants=consts),
          "dims that are not multiples of 32 are refused before anything is built")
    check(refuses(make_terrain, 32, 32, heights=[0.0] * 5),
          "a height field of the wrong length is refused, not padded")
    check(refuses(make_terrain, 32, 32, table_a=b"\x00\x01", table_b=b"\x00"),
          "and tile tables of different lengths are refused")


