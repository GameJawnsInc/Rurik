def section4(ar, mi):
    print(f"\n-- 4. row {TARGET_ROW} rebuilt from its parameters, and the census")
    entry = next(e for e in ar.entries if e.index == TARGET_ROW)
    source = ar.read(entry)
    mf, rep = build_like(TARGET_ROW, ar, index=mi)
    out = mf.encode()

    check(out == source, "BYTE-IDENTICAL to the archive's own map file",
          f"{len(out)} vs {len(source)} bytes")
    check(len(source) == EXPECT_TOTAL and len(rep.chunks) == EXPECT_CHUNKS,
          f"the target is still {EXPECT_TOTAL} B over {EXPECT_CHUNKS} chunks",
          f"{len(source)} B, {len(rep.chunks)} chunks")
    check(rep.donor_row != TARGET_ROW,
          "the FINDINGS 14 constants came from a DIFFERENT map",
          f"donor row {rep.donor_row} -- which is what makes the equality above "
          f"evidence for FINDINGS 14 rather than a tautology")

    # -- the census, with floors --------------------------------------------
    print(f"   {rep.generated} B generated ({rep.pct(rep.generated):.2f}%), "
          f"{rep.carried} B carried ({rep.pct(rep.carried):.2f}%)")
    check(rep.total == len(source) == rep.framing + rep.payload_bytes,
          "the census accounts for every byte of the file",
          f"{rep.framing} framing + {rep.payload_bytes} payload")
    check(rep.generated + rep.carried == rep.total,
          "and each byte is counted exactly once, generated or carried")
    check(rep.generated >= EXPECT_GENERATED,
          f"generated bytes clear the floor of {EXPECT_GENERATED}",
          f"{rep.generated} B")
    check(rep.pct(rep.generated) >= EXPECT_PCT,
          f"which is at least {EXPECT_PCT}% of the file",
          f"{rep.pct(rep.generated):.2f}%")
    check(rep.carried <= EXPECT_CARRIED,
          f"carried bytes stay at or under {EXPECT_CARRIED}", f"{rep.carried} B")
    check(rep.borrowed == EXPECT_BORROWED == sum(BORROWED_SIZES.values()),
          "232 of those carried bytes are the five FINDINGS 14 constants",
          f"{rep.borrowed} B")
    check(rep.strict_generated >= EXPECT_STRICT
          and rep.terrain_verbatim == rep.generated - rep.strict_generated,
          f"the STRICTER figure clears {EXPECT_STRICT} B too",
          f"{rep.strict_generated} B ({rep.pct(rep.strict_generated):.2f}%) once "
          f"{rep.terrain_verbatim} B of terrain arrays are subtracted")

    carried = rep.carried_chunks()
    check(len(carried) == EXPECT_CARRIED_KINDS
          and sum(c.size for c in carried) == rep.carried,
          f"{EXPECT_CARRIED_KINDS} chunks are carried and each is NAMED",
          ", ".join(f"0x{c.chunk_id:08X}" for c in carried))
    check(all(c.how for c in carried) and all(c.how for c in rep.chunks),
          "every chunk in the report says how its bytes were produced")
    borrowed_named = {c.chunk_id for c in carried if c.chunk_id in BORROWED_IDS}
    check(borrowed_named == set(BORROWED_IDS),
          "all five constants are reported as carried, none as generated")
    gen_ids = {c.chunk_id for c in rep.generated_chunks()}
    check(gen_ids == {TERRAIN_CHUNK, MAP_PARAMS_CHUNK, PATHING_CHUNK,
                      0x21000002, 0x21000009},
          "and the generated set is terrain, map parameters, path and the two "
          "Dependencies chunks", f"{sorted(hex(i) for i in gen_ids)}")

    sizes = {c.chunk_id: c.size for c in rep.chunks}
    check(sizes.get(TERRAIN_CHUNK) == 7165 and sizes.get(PATHING_CHUNK) == 419
          and sizes.get(MAP_PARAMS_CHUNK) == 41,
          "the three big generated chunks are the measured sizes",
          "terrain 7,165, path 419, map parameters 41")

    # -- what the terrain was actually built from ---------------------------
    params = rep.terrain_params
    arrays = [k for k, v in params.items()
              if isinstance(v, (bytes, bytearray, list)) and k != "order"]
    check(set(arrays) <= {"table_a", "table_b"},
          "row 46196's 7,165-byte terrain chunk came from NUMBERS",
          f"the only array inputs are the two 4-byte tile tables: {arrays}")
    check(params.get("shadow") is None,
          "its shadow block is regenerated by the run coder, not carried",
          "all-clear, and trnshadow emits the corpus-minimum 544 bytes")
    check(isinstance(params.get("heights"), float)
          and isinstance(params.get("tiles"), int),
          "the height field is one float and the tile field one byte value",
          f"heights={params.get('heights')}, tiles={params.get('tiles')}")
    return source, mf, rep


