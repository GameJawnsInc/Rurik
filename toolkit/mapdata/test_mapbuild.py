# An independent chunk walk. Imports nothing from mapfile or mapbuild: every
# per-chunk claim below is only evidence because it is read back out of the
# emitted bytes by different code.

def walk(blob):
    """[(chunk_id, payload)] out of an `ffna` file, or a ValueError."""
    if len(blob) < 5 or blob[:4] != b"ffna":
        raise ValueError(f"not an ffna file: {blob[:4]!r}")
    out, p = [], 5
    while p < len(blob):
        if p + 8 > len(blob):
            raise ValueError(f"chunk header runs off the end at {p}")
        cid = int.from_bytes(blob[p:p + 4], "little")
        size = int.from_bytes(blob[p + 4:p + 8], "little")
        body = p + 8
        if body + size > len(blob):
            raise ValueError(f"chunk 0x{cid:08X} declares {size} at {body}")
        out.append((cid, bytes(blob[body:body + size])))
        p = body + size
    return out


def chunk_map(blob):
    return dict(walk(blob))


def refuses(fn, *a, **kw):
    """True if the call raises ValueError -- a refusal, not a crash."""
    try:
        fn(*a, **kw)
    except ValueError:
        return True
    except Exception:
        return False
    return False


def holds(fn):
    """Evaluate a predicate over possibly-broken bytes. Never raises."""
    try:
        return bool(fn())
    except Exception:
        return False


def attempt(fn):
    """Like `holds`, but returns the VALUE (or None). Never raises.

    Written after `holds` was used where a value was wanted: `bool(dict)` is
    True, so three checks that should have read chunks out of a rebuilt file
    silently compared nothing and went red for the wrong reason.
    """
    try:
        return fn()
    except Exception:
        return None


def terrain_records(payload):
    """[(tag, body offset, size)] out of a terrain chunk, `int.from_bytes` only.

    Its own walker so the offsets this test reads terrain values at are not the
    ones `terrain.py` wrote them at. The header is EIGHT bytes here and TWELVE
    in the pathing chunk; using the wrong one desyncs the first record.
    """
    out, p = [], 8
    while p < len(payload):
        tag = payload[p]
        size = int.from_bytes(payload[p + 1:p + 5], "little")
        out.append((tag, p + 5, size))
        p = p + 5 + size
    return out


def guarded(fn, *a):
    """An exception inside a section becomes a named FAIL, not a traceback."""
    try:
        return fn(*a)
    except Exception as exc:
        check(False, f"section {fn.__name__} ran to completion",
              f"{type(exc).__name__}: {exc}")
        return None


def placeholder_constants():
    """OUR zero bytes at FINDINGS 14's measured sizes -- never ArenaNet's.

    This is what lets sections 1 and 3 run the whole assembly path on a bare
    machine. The resulting map is NOT loadable: a zeroed Header fails the
    client's own signature gate, and nothing here pretends otherwise. What it
    exercises is the builder's order, framing, census and refusals, all of which
    are ours.
    """
    return {cid: bytes(n) for cid, n in BORROWED_SIZES.items()}


