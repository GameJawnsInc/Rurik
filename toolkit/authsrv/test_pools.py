def skill_row(world, skill, build, used=None):
    """The skill's row, by a STATED RULE (CASTAI-Z1, R8).

    Content's `skills` table is the PLAYER CORPUS of build 38797
    (`skilltable.player_corpus`: equip_family 1, PvP excluded). A skill it
    lacks is read from the client table of the build the capture was made
    with, and accepted there ONLY as a PvP-only split of a player skill
    (pvp_only, equip_family 0, `linked_id` a content row). Anything else raises
    MissingRow. `used` collects {skill: (build, linked_id)} for the checks."""
    import content
    try:
        return world.get("skills", str(skill))
    except content.ContentError:
        pass
    if build is None:
        raise MissingRow(f"skill {skill}: not in content and no build to read")
    import skilltable
    data, base, count = _client_table(build)
    if not 0 <= skill < count:
        raise MissingRow(f"skill {skill} is past build {build}'s {count}-record table")
    r = skilltable.parse_record(data, base, skill)
    if (r["pvp_only"] and r["equip_family"] == 0
            and str(r["linked_id"]) in world.rows("skills")):
        if used is not None:
            used[skill] = (build, r["linked_id"])
        return r
    raise MissingRow(f"skill {skill} (build {build}) is not in content and is not "
                     f"a PvP split of a player skill")


def outside_player_corpus(skill, build):
    """True when `build`'s own client row for `skill` exists and is NOT in the
    player corpus (`skilltable.player_corpus`: equip_family 1, PvP clear) --
    the stated reason content's `skills` table lacks it. False for anything
    else, including an id past the table or no build to read."""
    if build is None:
        return False
    import skilltable
    data, base, count = _client_table(build)
    if not 0 <= skill < count:
        return False
    r = skilltable.parse_record(data, base, skill)
    return not (r["equip_family"] == 1 and not r["pvp_only"])


