def fake():
    """(sent, send, state) -- the three things every glue section starts with."""
    sent = []
    send = lambda op, vals, why="": sent.append((op, vals, why))    # noqa: E731
    return sent, send, {"agents": {}}


def props(sent, opcode, prop):
    """Every value list on `opcode` carrying property id `prop`."""
    return [v for op, v, _w in sent if op == opcode and v and v[0] == prop]


