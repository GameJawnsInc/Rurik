    """The RB2 signature as it stood from 2026-09-17 to 2026-09-29: FLOOR.
    FAILED on 20260929T100038 (89 -> 18, 93 -> 19, 74 -> 15, 78 -> 16, 84 ->
    17 on the wire; this says 17, 18, 14, 15, 16). Kept, not deleted: section
    2b asserts it still classifies every pre-Z2 row exactly as the round rule
    does, and that it leaves FLOOR_STRAYS_ON_Z2 stray on the witness tape."""
    pips, mx = key
