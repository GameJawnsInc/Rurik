def _scan_corpus(live):
    """Every generic-property event in the live corpus, joined per agent.

    `live` is the directory `_live_corpus_dir()` resolved. The caller catches
    nothing: a connection that fails to load and is not declared gapped by its
    own manifest propagates as a crash.

    Returns (totals, regen_rows, spend_rows, gain_values, cast_rows). Each
    regen and spend row carries the agent's own most recent property-41 maximum
    -- the join that makes the integrality check possible -- and each spend also
    carries the skill it belongs to. Each cast row says whether that agent ever
    received a property 41 in this connection (`own`) and whether a property 62
    rode the same batch (`spend`), which is what section 2e's contingency table
    is built from.

    THE CAST JOIN IS BY TIME AND NOT BY STREAM ORDER, and that cost a red run
    before it was written down. A property-62 spend and the property-60/50/48
    that names the skill ride the SAME BATCH (lag 0.000 s for 45 of 45), and the
    SPEND COMES FIRST in the stream, also 45 of 45. So the streaming reading --
    "attribute a spend to the last cast already seen" -- attributes every single
    one to the PREVIOUS cast, and scores 18 of 45 with a plausible-looking mix
    of zero-cost skills in the miss list. Joining on `cast_t <= spend_t` instead
    scores 45 of 45. Section 2c checks the ordering itself so this stays a
    measured fact rather than a comment.
    """
    import tape
    from codec import Codec

    codec = Codec()
    totals = _new_totals()
    regen, spends, gains, cast_rows = [], [], [], []

    import livewire
    for stamp in sorted(os.listdir(live)):
        cap = os.path.join(live, stamp)
        if not os.path.isdir(cap):
            continue
        totals["captures"] += 1
        declared = livewire.declared_gaps(cap)
        for conn in tape.channel_files(cap):
            # A GAPPED CONNECTION is set aside ONLY because its own capture's
            # manifest declares it (CASTAI-Z1, livewire.declared_gaps), and it
            # must STILL be refused. No blanket except: any other connection
            # that fails to load is a crash, not a quiet `continue`.
            if conn["connection"] in declared:
                try:
                    tape.load_tape(cap, conn["connection"])
                    refused = False
                except tape.TapeError:
                    refused = True
                totals["set_aside"].append((stamp, conn["connection"], refused))
                print(f"  (set aside: {stamp} {conn['connection']} -- its manifest "
                      f"declares gaps {declared[conn['connection']]})")
                continue
            info, events = tape.load_tape(cap, conn["connection"])
            msgs, _receipt = tape.decode_all(events, codec, "GAME_SMSG", 0)
            build = _capture_build(cap, conn["path"])
            _scan_connection(msgs, stamp, conn["connection"], build, totals,
                             regen, spends, gains, cast_rows)
    return totals, regen, spends, gains, cast_rows


