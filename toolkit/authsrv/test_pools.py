def section_quantum():
    """THE QUANTUM: 0.33 as an f32, against the 1/3 every source states.

    Five bit patterns, one check each, so a failure names the cluster that
    moved. Then the negative that makes them mean something.
    """
    print("1. the quantum -- f32(0.33)*pips/max, bit for bit")

    for rate, (pips, mx, n) in sorted(RETAIL_RATES.items()):
        got = pools.wire_regen_rate(pips, mx)
        LEDGER.ok(got == rate,
                  f"{pips} pips over {mx} energy is exactly {rate!r}",
                  f"got {got!r}; retail sent this f32 {n} time(s). Compared "
                  f"with == and not a tolerance -- an f32 the client stores and "
                  f"animates from either matches or does not")

    nominal = [f32(p / (3.0 * m)) for p, m, _n in RETAIL_RATES.values()]
    LEDGER.ok(not (set(nominal) & set(RETAIL_RATES)),
              "and the NOMINAL 1/3 energy per second reproduces NONE of the five",
              f"{[round(x, 8) for x in nominal]} against "
              f"{[round(x, 8) for x in sorted(RETAIL_RATES)]}. Every source "
              f"states a pip as one third of a point per second; the client's "
              f"constant is 0.33f. 1% of the regeneration rate, which is 40 "
              f"seconds of energy over a 20-minute run -- and, more usefully, "
              f"a difference our own captures can SEE")

    as_double = sum(1 for rate, (p, m, _n) in RETAIL_RATES.items()
                    if f32(0.33 * p / m) == rate)
    LEDGER.ok(as_double < len(RETAIL_RATES),
              "and 0.33 as a DOUBLE misses some of them -- the constant is a float",
              f"{as_double} of {len(RETAIL_RATES)} match when 0.33 is not "
              f"rounded to f32 first. That is the evidence for `float` rather "
              f"than `double` in the client, and it is the whole reason "
              f"`wire_regen_rate` rounds the constant before it multiplies")

    LEDGER.ok(pools.wire_regen_rate(3, 25) == f32(0.0396),
              "and this finally EXPLAINS content/world.toml's float_43 = 0.0396",
              "3 pips over a 25-energy pool. That constant was copied from "
              "gw-preservation, whose own comment says 'REVERSE THIS MORE', and "
              "`agents.py` records it as a GUESS. It is a ranger's regeneration "
              "on a ranger's pool, it is internally consistent with "
              "PLAYER_ENERGY = 25, and it is now a measured value rather than "
              "an inherited one")

    LEDGER.ok(pools.wire_regen_rate(0, 25) == 0.0,
              "zero pips is exactly 0.0, which is what a death sends",
              "OBSERVED twice: property 43 goes to 0.0 in the same batch as the "
              "death bit, once at max 25 and once at max 22")
    try:
        pools.wire_regen_rate(2, 0)
        refused = None
    except pools.PoolError as ex:
        refused = str(ex)
    LEDGER.ok(refused is not None,
              "and a pool of zero REFUSES rather than dividing",
              "the rate is a fraction OF THE POOL; an inf reinterpreted into "
              "the dword slot is a number the client will animate towards")

    print("\n1b. the property ids agree with the server's own vocabulary")
    try:
        import agents
        same = (pools.GV_ENERGY_GAIN == agents.GV_ENERGY_GAIN
                and pools.GV_ENERGY_SPENT == agents.GV_ENERGY_SPENT
                and pools.GV_ENERGY_REGEN == agents.PROP_UNKNOWN_FLOAT_43)
        LEDGER.ok(same,
                  "52, 62 and 43 match agents.py's declarations",
                  f"{pools.GV_ENERGY_GAIN}/{pools.GV_ENERGY_SPENT}/"
                  f"{pools.GV_ENERGY_REGEN}. They are restated in pools.py "
                  f"rather than imported so the module keeps effects.py's "
                  f"property of importing nothing from the server -- which "
                  f"leaves exactly one way for the two copies to drift, and "
                  f"this is it")
    except Exception as ex:                                    # noqa: BLE001
        LEDGER.skip("the id cross-check", f"agents.py unavailable ({ex})")


