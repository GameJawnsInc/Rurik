def section_refusal_silent():
    """--refusal-silent is the A/B arm, and an untested arm is not an arm.

    SKILLS-R2 (studies/skills 37) rests entirely on this flag reproducing the
    pre-2026-08-22 server: one press, two runs, one flag apart. If it ever
    stopped suppressing, the A/B would compare two IDENTICAL arms and report
    "no difference" -- which is exactly the shape of the wrong answer that
    session's png stride bug produced, and it would be just as convincing.

    So both directions are asserted here, in-process, with no socket.
    """
    print("\n11j. --refusal-silent suppresses the whole answer, both ways")
    if _needs_skill_rows("11j. --refusal-silent suppresses the whole answer, both ways"):
        return
    import authsrv

    def refuse_with(silent):
        sent, send, state = fake()
        authsrv.player_energy(state).current = 1.0
        was = authsrv.REFUSAL_SILENT
        authsrv.REFUSAL_SILENT = silent
        try:
            authsrv.handle_skill_press([0, 194, 0, 0], send, state, 0,
                                       authsrv.GAME_CMSG_USE_SKILL)
        finally:
            authsrv.REFUSAL_SILENT = was
        return [op for op, _v, _w in sent]

    loud = refuse_with(False)
    quiet = refuse_with(True)

    LEDGER.ok(quiet == [],
              "with the flag ON a refused press sends NOTHING",
              f"{quiet} -- this is the server we were until 2026-08-22, and "
              f"reproducing it exactly is the flag's whole job. Anything on "
              f"the wire here makes the SKILLS-R2 arms differ by more than "
              f"one thing")

    LEDGER.ok(loud == [authsrv.GAME_SMSG_CHAT_MESSAGE_CORE,
                       authsrv.GAME_SMSG_CHAT_MESSAGE_SERVER,
                       authsrv.GAME_SMSG_SKILL_REFUSED],
              "and with it OFF the full three-message batch goes out",
              f"{loud} -- the DEFAULT, because retail answers 43 of 43 "
              f"declined presses. A flag that defaulted the other way would "
              f"make our own shipped behaviour the experimental arm")

    LEDGER.ok(loud != quiet,
              "so the two arms genuinely differ, which is what makes the A/B "
              "an A/B",
              "stated as its own check rather than left implied: two arms that "
              "silently became identical would still pass both checks above if "
              "either were written loosely, and would read as a clean null")


