def morale_scaled(key, morales):
    """Is (pips, max) a BASE row's pool under one of the observed morales?

    max == ROUND(20 x morale / 100) + the base row's armour bonus, the pips
    unchanged (or zero: the death itself). CASTAI-Z2 (2026-09-29): this rounded
    where it used to floor -- see Z2_TAPE and `morale_scaled_floor_as_written`,
    which is kept as the record of the rule that failed and as this one's
    known-bad arm. Integer arithmetic, half-up; no half is reachable."""
    pips, mx = key
    for m in morales:
        if m is None or m >= 100:
            continue
        for bp, bmax in BASE_PIPS:
            if pips in (0, bp) and mx == (20 * m + 50) // 100 + (bmax - 20):
                return True
    return False


